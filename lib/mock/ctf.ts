import type { MockChallengeCategory, MockChallenge, MockResearcherLevel } from "./researcher-dashboard";
import artifactManifest from "./ctf-artifacts.manifest.json";

export type CtfCategoryId = "web" | "crypto" | "reverse-engineering" | "binary-pwn" | "forensics" | "network";

/** One downloadable challenge artifact (a pcap, image, disk image, memory dump...), served
 * statically from public/ctf-artifacts/. `path` is the public URL. */
export type CtfArtifactFile = { name: string; path: string; size: number; contentType: string };

/** The solvable material for a challenge, generated by scripts/ctf-artifacts/ and merged
 * onto each challenge below from lib/mock/ctf-artifacts.manifest.json:
 *  - `embeddedData`: text shown inline on the challenge page (a code/response snippet,
 *    ciphertext, JWT, disassembly listing, etc.) that the player reads and reasons about.
 *  - `artifacts`: downloadable files the technique is applied to.
 * The plaintext flag is NEVER here (see the file-header note): the manifest contains only
 * challenge material, and each artifact was verified (npm run ctf:artifacts:verify) to yield
 * the flag whose hash the CTF migration seeds -- the flag itself stays server-side only. */
type CtfArtifactManifestEntry = { embed?: string; files?: CtfArtifactFile[] };
const ARTIFACT_MANIFEST = artifactManifest as Record<string, CtfArtifactManifestEntry>;

export type MockCtfCategory = {
  id: CtfCategoryId;
  label: string;
  description: string;
  challengeCount: number;
};

export type CtfDifficulty = "Easy" | "Medium" | "Hard" | "Insane";

/** Points come from a fixed per-difficulty table, never hand-tuned per challenge -- so a
 * difficulty badge and its point value can never silently contradict each other. */
export const CTF_DIFFICULTY_POINTS: Record<CtfDifficulty, number> = { Easy: 100, Medium: 250, Hard: 500, Insane: 1000 };

export type MockCtfTrack = { id: string; label: string; description: string; challengeIds: string[] };

export type MockCtfChallenge = {
  id: string;
  slug: string;
  title: string;
  categoryId: CtfCategoryId;
  difficulty: CtfDifficulty;
  points: number;
  prompt: string;
  flagFormatHint: string;
  hints: string[];
  solveCount: number;
  estimatedMinutes: number;
  trackId?: string;
  /** ISO date -- only set for challenges recent enough to earn a "New" badge; omitted
   * means "not new," never a fabricated release date. */
  releasedAt?: string;
  /** Inline challenge material (code/response snippet, ciphertext, JWT, disassembly...),
   * merged from the artifact manifest. Never contains the plaintext flag. */
  embeddedData?: string;
  /** Downloadable artifacts (pcap, image, disk image, memory dump...) the technique is
   * applied to, merged from the artifact manifest. */
  artifacts?: CtfArtifactFile[];
};
// The plaintext flag is deliberately NOT a field here as of docs/decisions/0072 -- it
// lives only, hashed, in the real `ctf_challenges.flag_hash` column
// (supabase/migrations/202609050001_ctf_server_verification_and_reputation.sql), so no
// code path can ever ship a plaintext flag to a client again. `submit_ctf_flag` compares
// a server-side hash; this file has no way to reintroduce the old client-side check.

function challenge(input: Omit<MockCtfChallenge, "points" | "embeddedData" | "artifacts">): MockCtfChallenge {
  const artifact = ARTIFACT_MANIFEST[input.id];
  return {
    ...input,
    points: CTF_DIFFICULTY_POINTS[input.difficulty],
    embeddedData: artifact?.embed,
    artifacts: artifact?.files,
  };
}

